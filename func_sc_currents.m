function [Ik3, Ik2, Ik1] = func_sc_currents(I1, I2, I0, U_nom)
    % FUNC_SC_CURRENTS Расчёт действующих значений токов короткого замыкания в кА.
    % Автор: Юнусов Шероз, ИРНИТУ, магистерская диссертация, 2026 г.
    % Версия: 1.2.2
    % Подраздел диплома: 3.4 «Модуль определения токов КЗ func_sc_currents.m»
    %
    % Перевод из о.е. в кА при Sбаз = 100 МВА: I_кА = |I_о.е.| · Uном·1000 / (√3·100).

    Ik3 = abs(I1) * (U_nom * 1000 / sqrt(3)) / 100;
    Ik2 = abs(I2) * (U_nom * 1000 / sqrt(3)) / 100;
    Ik1 = abs(3 * I0) * (U_nom * 1000 / sqrt(3)) / 100;
end
