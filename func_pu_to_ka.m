function I_kA = func_pu_to_ka(I_pu, U_nom)
    % FUNC_PU_TO_KA Перевод тока из о.е. (Sбаз=100 МВА) в кА при напряжении U_nom (кВ).
    % Автор: Юнусов Шероз, ИРНИТУ, магистерская диссертация, 2026 г.
    % Версия: 1.4.0
    % Подраздел диплома: 3.4 «Модуль определения токов КЗ»
    %
    % I_базис = Sбаз / (√3·Uном) ⇒ I_кА = |I_о.е.| · Uном·1000 / (√3·100).

    I_kA = abs(I_pu) * (U_nom * 1000 / sqrt(3)) / 100;
end
