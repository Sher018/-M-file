  t(key, vars) {
    const pack = this.dict[this.lang] || this.dict.ru;
    let s = pack[key] ?? this.dict.ru[key] ?? key;
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        s = s.replace(`{${k}}`, String(v));
      });
    }
    return s;
  },
  setLang(lang) {
    if (!this.dict[lang]) return;
    this.lang = lang;
    localStorage.setItem("bridge-lang", lang);
    document.documentElement.lang = lang === "tg" ? "tg" : lang;
    window.dispatchEvent(new CustomEvent("bridge:lang"));
  },
  loc(obj) {
    if (!obj) return "";
    if (typeof obj === "string") return obj;
    return obj[this.lang] || obj.ru || obj.en || Object.values(obj)[0] || "";
  },
