function B = func_breaking_thermal(Ik, tau_s, t_break_s)
    % FUNC_BREAKING_THERMAL Ток отключения и термически эквивалентный ток КЗ.
    % Автор: Юнусов Шероз, ИРНИТУ, магистерская диссертация, 2026 г.
    % Версия: 1.4.0
    % Подраздел диплома: 3.5 «Ударный ток и токи для выбора аппаратов»
    %
    % Ik         — начальное действующее значение тока КЗ (I"k), кА;
    % tau_s      — постоянная времени апериодической составляющей, с;
    % t_break_s  — расчётное время отключения (по умолчанию 0.2 с).
    %
    % Возвращает структуру B (далёкое от генератора КЗ, I"k ≈ Ib):
    %   i_dc      — апериодическая составляющая в момент t, кА;
    %   Ib        — периодический ток отключения (= I"k), кА;
    %   Ib_asym   — полный (асимметричный) ток отключения, кА;
    %   I_th      — термически эквивалентный ток за время t, кА;
    %   m, n      — коэффициенты теплового действия (n = 1 для далёкого КЗ).
    %
    % Тепловой импульс (интеграл Джоуля): B_J = I"k²·[t + τ·(1 − e^(−2t/τ))],
    % отсюда I_th = I"k·√(1 + (τ/t)·(1 − e^(−2t/τ))), m = (τ/t)·(1 − e^(−2t/τ)).

    if nargin < 3 || isempty(t_break_s)
        t_break_s = 0.2;
    end
    if ~(isfinite(tau_s) && tau_s > 0)
        tau_s = 0.05;
    end
    t = max(t_break_s, 1e-6);

    B.i_dc = sqrt(2) * Ik * exp(-t / tau_s);
    B.Ib = Ik;
    B.Ib_asym = sqrt(Ik^2 + B.i_dc^2);

    B.m = (tau_s / t) * (1 - exp(-2 * t / tau_s));
    B.n = 1;
    B.I_th = Ik * sqrt(B.m + B.n);
    B.t_break = t;
end
