function [I1, I2, I0] = func_sym_components(E, Z1, Z2, Z0)
    % FUNC_SYM_COMPONENTS Расчёт симметричных составляющих токов короткого замыкания.
    % Автор: Юнусов Шероз, ИРНИТУ, магистерская диссертация, 2026 г.
    % Версия: 1.2.2
    % Подраздел диплома: 3.3 «Модуль расчёта симметричных составляющих func_sym_components.m»
    %
    % I1 = E/Z1;  I2 = E/(Z1+Z2);  I0 = E/(Z1+Z2+Z0) — метод Фортескью.

    I1 = E ./ Z1;
    I2 = E ./ (Z1 + Z2);
    I0 = E ./ (Z1 + Z2 + Z0);
end
