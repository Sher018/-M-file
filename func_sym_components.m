function [I1, I2, I0] = func_sym_components(E, Z1, Z2, Z0)
    % FUNC_SYM_COMPONENTS Расчёт токов КЗ методом симметричных составляющих.
    % Автор: Юнусов Шероз, ИРНИТУ, магистерская диссертация, 2026 г.
    % Версия: 1.4.0
    % Подраздел диплома: 3.3 «Модуль расчёта симметричных составляющих func_sym_components.m»
    %
    % Возвращает расчётные токи для перевода в кА (func_sc_currents):
    %   I1 = E/Z1                  — трёхфазное КЗ;
    %   I2 = √3·E/(Z1+Z2)          — двухфазное КЗ (междуфазное, множитель √3);
    %   I0 = E/(Z1+Z2+Z0)          — однофазное КЗ (далее берётся 3·I0).
    %
    % Множитель √3 в I2 соответствует действующему току междуфазного КЗ:
    % при Z2 = Z1 получаем Iк2 = (√3/2)·Iк3 ≈ 0,866·Iк3.

    I1 = E ./ Z1;
    I2 = sqrt(3) * E ./ (Z1 + Z2);
    I0 = E ./ (Z1 + Z2 + Z0);
end
